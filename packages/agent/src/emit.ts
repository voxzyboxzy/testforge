import type { AcceptanceCase, LocatorPlan } from './criteria';
import { confirmationExpr, submitExpr, tsString } from './locators';

function actionLines(testCase: AcceptanceCase, plan: LocatorPlan): string[] {
  const lines: string[] = [];
  for (const step of testCase.steps) {
    if (step.kind === 'fill') {
      lines.push(`  await page.getByLabel(${tsString(step.label)}, { exact: true }).fill(${tsString(step.value)});`);
    } else if (step.kind === 'select') {
      lines.push(`  await page.getByLabel(${tsString(step.label)}, { exact: true }).selectOption(${tsString(step.value)});`);
    } else if (step.kind === 'check') {
      lines.push(`  await page.getByRole('radio', { name: ${tsString(step.name)}, exact: true }).check();`);
    } else if (step.kind === 'click') {
      const target = submitExpr(plan.submit);
      for (let count = 0; count < step.count; count += 1) {
        lines.push(`  await ${target}.click();`);
      }
    } else if (step.kind === 'axe') {
      lines.push('  const results = await new AxeBuilder({ page }).analyze();');
      lines.push("  const serious = results.violations.filter((violation) => violation.impact === 'serious' || violation.impact === 'critical');");
      lines.push('  expect(serious, serious.map((violation) => violation.id).join(", ")).toEqual([]);');
    }
  }
  return lines;
}

function expectLines(testCase: AcceptanceCase, plan: LocatorPlan): string[] {
  const lines: string[] = [];
  const confirmation = confirmationExpr(plan.confirmation);
  if (testCase.expect.alert) {
    lines.push(`  await expect(page.getByRole('alert')).toContainText(${tsString(testCase.expect.alert)});`);
  }
  if (testCase.expect.confirmation) {
    lines.push(`  await expect(${confirmation}).toContainText(${tsString(testCase.expect.confirmation)});`);
  }
  if (testCase.expect.noConfirmation) {
    lines.push(`  await expect(${confirmation}).toHaveCount(0);`);
  }
  if (testCase.expect.submissions != null) {
    lines.push(`  await expect.poll(async () => submissionCount(page)).toBe(${testCase.expect.submissions});`);
  }
  return lines;
}

/** Render the acceptance cases as a Playwright spec. Locator choices come only from the plan. */
export function emitSpec(cases: AcceptanceCase[], plan: LocatorPlan): string {
  const tests = cases
    .map((testCase) => {
      const body = [...actionLines(testCase, plan), ...expectLines(testCase, plan)].join('\n');
      return `test(${tsString(testCase.title)}, async ({ page }) => {
  // case:${testCase.id}
  const locale = ${tsString(testCase.locale)} as const;
  await page.goto(openUrl(locale));
${body}
});`;
    })
    .join('\n\n');

  return `// Generated by TestForge from criteria/job-application.yaml.
// Locator repairs may change getBy* calls only. Expected outcomes are frozen.
import { expect, test, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

const baseURL = process.env.TESTFORGE_BASE_URL ?? 'http://127.0.0.1:4173';

function openUrl(locale: 'en' | 'es') {
  const url = new URL(baseURL);
  url.searchParams.set('lang', locale);
  if (process.env.TESTFORGE_BUGS) url.searchParams.set('bugs', process.env.TESTFORGE_BUGS);
  if (process.env.TESTFORGE_ATTEMPT) url.searchParams.set('attempt', process.env.TESTFORGE_ATTEMPT);
  return url.toString();
}

async function submissionCount(page: Page) {
  const response = await page.request.get(new URL('/api/submissions', baseURL).toString());
  const body = (await response.json()) as unknown[];
  return body.length;
}

test.beforeEach(async ({ request }) => {
  const response = await request.delete(new URL('/api/submissions', baseURL).toString());
  expect(response.ok()).toBeTruthy();
});

${tests}
`;
}
